import SwiftUI

/// Огибающая интерфейса — та же, что у сигнала.
///
/// Полосы в этой программе живут по одному закону: быстро вверх, медленно вниз.
/// Удар не должен смазаться, а свет обязан угасать, а не пропадать. Числа взяты
/// не с потолка — они уже есть в коде: обработка звука сглаживает полосы за 25 мс
/// на рост и 250 на спад, `SpectrumSmoother` рисует их за 45 и 380.
///
/// Содержимое этому закону подчинялось всегда, а обвязка вокруг него моргала
/// симметричными переходами и мгновенными скачками. Свет так себя не ведёт —
/// теперь и окно не ведёт: всё, что загорается, загорается быстро, и всё, что
/// гаснет, остывает втрое дольше.
public enum Motion {

    /// Разгорание: круто в начале, с длинным успокоением в конце.
    public static let attack = Animation.timingCurve(0.16, 1, 0.3, 1, duration: 0.12)

    /// Угасание — втрое дольше разгорания, как у полосы на ленте.
    public static let release = Animation.easeOut(duration: 0.38)

    /// Отклик органа под курсором.
    public static let feedback = Animation.easeOut(duration: 0.10)

    /// Раскрытие раздела: движение сюжетное, а не световое, — потому симметричное.
    public static let disclosure = Animation.easeInOut(duration: 0.15)

    /// Разгорание или угасание — по направлению перехода.
    public static func envelope(rising: Bool) -> Animation { rising ? attack : release }

    /// Зажигание гряды — единственное место, где движению дано время.
    ///
    /// Дольше обычного отклика намеренно: пуск и есть то, ради чего программу
    /// открыли, и полосам дано разгореться, а не мигнуть. Задержкой это не
    /// читается, потому что всё остальное — кнопка, состояние, счётчик —
    /// меняется мгновенно; тянется только свет.
    public static let ignition = Animation.timingCurve(0.16, 1, 0.3, 1, duration: 0.45)

    /// Остывание втрое дольше зажигания: свет не выключают, он гаснет.
    public static let extinction = Animation.easeOut(duration: 0.62)

    /// Зажигание или остывание гряды.
    public static func light(rising: Bool) -> Animation { rising ? ignition : extinction }

    /// Разгорание шестнадцати полос: бас загорается первым, верх последним.
    ///
    /// Не украшение и не «список с задержкой»: ровно так лента и отзывается
    /// на первый такт — низ идёт раньше, потому что в музыке он и приходит раньше.
    /// Вся гряда укладывается в 0.36 от полного хода, дальше полосы просто живут.
    static func bandGate(_ progress: Double, index: Int, count: Int) -> Double {
        guard count > 1 else { return progress }
        let start = 0.36 * Double(index) / Double(count - 1)
        let span = 1 - 0.36
        let local = (progress - start) / span
        return min(1, max(0, local))
    }
}
