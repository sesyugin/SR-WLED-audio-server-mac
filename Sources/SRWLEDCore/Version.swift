/// Версия программы — одно место на весь проект.
///
/// Отсюда её берут и консольная версия по `--version`, и сборщик бандла:
/// `scripts/build-app.sh` вынимает обе строки регулярным выражением и кладёт
/// в Info.plist. Формат строк менять только вместе со скриптом — он проверяет,
/// что достал непустое значение, и падает, если не достал.
public enum Version {
    /// Версия, видимая человеку: CFBundleShortVersionString и вывод --version.
    public static let current = "0.3.0"
    /// Номер сборки: CFBundleVersion. Растёт при каждом выпуске, даже если
    /// видимая версия та же.
    public static let build = "3"
}
